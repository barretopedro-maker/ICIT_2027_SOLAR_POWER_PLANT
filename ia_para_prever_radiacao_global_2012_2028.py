FEATURES = ['sin_hora','cos_hora','sin_ano','cos_ano','climatologia_kJ_m2'] + [
    f'lag_{lag}h' for lag in DEFASAGENS_HORAS] + ['media_ultimas_24h']

def tabela_features(s_preenchida, clima):
    idx=s_preenchida.index
    h=idx.hour.to_numpy()
    ang_dia=2*np.pi*h/24
    ang_ano=2*np.pi*(idx.dayofyear.to_numpy()-1)/365.25
    mat = {
       'sin_hora':np.sin(ang_dia), 'cos_hora':np.cos(ang_dia),
       'sin_ano':np.sin(ang_ano),'cos_ano':np.cos(ang_ano),
       'climatologia_kJ_m2':[valor_climatologia(t,clima) for t in idx]
    }
    for lag in DEFASAGENS_HORAS:
        mat[f'lag_{lag}h']=s_preenchida.shift(lag).to_numpy()
    mat['media_ultimas_24h'] = s_preenchida.shift(1).rolling(24,min_periods=24).mean().to_numpy()
    return pd.DataFrame(mat,index=idx)[FEATURES]


def treinar_rf(s_bruta, n_arvores=RF_ESTIMADORES):
    clima=criar_climatologia(s_bruta)
    s_preenchida=preencher_entradas(s_bruta,clima)
    fx=tabela_features(s_preenchida,clima)
    treino_ok=s_bruta.notna() & fx.notna().all(axis=1)
    X=fx.loc[treino_ok].to_numpy(dtype=np.float32)
    y=s_bruta.loc[treino_ok].to_numpy(dtype=np.float32)
    rf=RandomForestRegressor(n_estimators=n_arvores,max_depth=RF_PROFUNDIDADE,
            min_samples_leaf=RF_FOLHA_MINIMA,random_state=SEMENTE,n_jobs=-1)
    rf.fit(X,y)
    print(f'RF ajustada: {X.shape[0]} instâncias, {X.shape[1]} atributos e {n_arvores} árvores.')
    return rf,clima,s_preenchida,fx,treino_ok

