"""## 17. Limitações e possibilidades de aprofundamento

1. **Interpretação da coluna.** A conversão em W/m² e kWh/m² pressupõe **acumulação durante 1 h**. Confirmar a ficha técnica da estação; não interpretar kJ/m² diretamente como watts.
2. **Noite e falta de medição.** O horário UTC local de nascer e pôr do Sol varia com a época; a máscara noturna usada é conservadora, porém ainda exige conferência do local. 2015, 2016, 2021, 2023 e 2024 têm lacunas diurnas relevantes; zeros inferidos permanecem rotulados.
3. **Validação temporal.** Os modelos são avaliados sem misturar dados futuros no treinamento e sem transformar lacunas em observações. O cenário avaliado é **previsão diária**, atualizado após observações disponíveis; projeções de 2027/2028 são muito mais difíceis.
4. **SARIMA.** A comparação de 2025 usa uma janela recente de ajuste e atualização do estado a cada dia; aumente a janela se o Colab tiver memória/tempo suficientes, sem alterar o período de teste.
5. **Estimativas energéticas.** `kWh/m²` e `W/m²` são calculáveis sem conhecer um equipamento. **Potência/energia elétrica FV** dependem de área, eficiência, perdas e, para módulos inclinados, plano dos módulos. A potência real ainda depende de temperatura, sombreamento, inversor e sujeira.
6. **Torque.** Radiação global, isoladamente, não permite calcular o torque de uma máquina elétrica ou um sistema de rastreamento solar. São necessários dados eletromecânicos do equipamento, não fornecidos pelas planilhas.
7. **Melhorias futuras.** Considerar previsões meteorológicas exógenas (nebulosidade, temperatura, umidade), posição solar calculada com latitude/longitude e fuso, decomposição GHI→DNI/DHI→POA, quantis e backtesting com múltiplos anos; comparar com modelos de referência sazonais antes de reivindicar superioridade de uma IA.

**Reprodutibilidade:** as células devem ser executadas de cima para baixo. Nenhuma etapa utiliza arquivos de previsões externas do notebook eólico, nem constantes como densidade do ar, coeficiente de potência e relação de ponta de pá.
"""