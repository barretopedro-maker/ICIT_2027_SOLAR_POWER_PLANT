"""## 14. Conversões físicas — energia solar disponível e geração FV opcional

Para dados **horários integrados**, as seguintes relações são usadas:

- **Irradiação da hora:** \(H_{\mathrm{kWh/m^2}} = H_{\mathrm{kJ/m^2}}/3600\).
- **Irradiância média na hora:** \(\overline G_{\mathrm{W/m^2}}=H_{\mathrm{kJ/m^2}}/3{,}6\).
- **Energia solar que incide numa área \(A\):** \(E_{inc}=H_{\mathrm{kWh/m^2}}\cdot A\).
- **Estimativa fotovoltaica simples (se houver parâmetros):** \(E_{FV}=H_{\mathrm{kWh/m^2}}\cdot A\cdot\eta\cdot PR\), e \(\overline P_{FV}=\overline G\cdot A\cdot\eta\cdot PR\).

**Importante:** `A`, `η` e `PR` são **parâmetros fotovoltaicos**, não equivalem à área varrida, coeficiente de potência ou velocidade angular de turbinas eólicas. Além disso, a projeção usa **radiação global horizontal (GHI)**; para estimar rendimento de módulos **inclinados**, será necessário transformar GHI para irradiância no plano dos módulos (POA), com inclinação, orientação, localização e dados ou hipóteses de decomposição direta/difusa. O resultado atual, se parametrizado, é uma **aproximação para superfície coincidente com o plano medido**, não um modelo completo de usina FV.

**Torque:** não existe conversão fisicamente justificada de irradiação global diretamente em torque. Por isso `Ta`, `ωR`, `λ`, `βCom`, `Ng` e os coeficientes aerodinâmicos do notebook de vento foram **deliberadamente excluídos**.
"""

