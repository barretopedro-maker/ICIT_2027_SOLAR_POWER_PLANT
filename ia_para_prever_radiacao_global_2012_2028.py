def criar_climatologia(s):
    valores = s.dropna()
    if valores.empty: raise ValueError('Não há dados de treinamento válidos.')
    return {'mes_hora':valores.groupby([valores.index.month,valores.index.hour]).median().to_dict(),
            'hora':valores.groupby(valores.index.hour).median().to_dict(),
            'global':float(valores.median())}


def valor_climatologia(t, c):
    return float(c['mes_hora'].get((t.month,t.hour),c['hora'].get(t.hour,c['global'])))


def preencher_entradas(s,c):
    # Retorna série regular; alvos ausentes continuam ausentes em `s` original.
    imputed = np.array([valor_climatologia(t,c) for t in s.index],dtype=float)
    vals = s.to_numpy(dtype=float)
    return pd.Series(np.where(np.isfinite(vals),vals,imputed),index=s.index,name='Lag_preenchida')

