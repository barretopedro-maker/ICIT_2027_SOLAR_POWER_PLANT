"""## 9. Previsão operacional com Random Forest: 24 horas à frente

A função abaixo gera as 24 previsões de um dia **recursivamente**, sem usar leituras desse mesmo dia; depois o dia é fechado com valores realmente conhecidos (ou previsões, onde o sensor falhou). Dessa forma não há *vazamento temporal* durante a avaliação. No modo `observado=None`, o mesmo código gera previsões futuras totalmente recursivas.
"""

def vetor_para_hora(t,historico,clima):
    ang_d=2*np.pi*t.hour/24
    ang_a=2*np.pi*(t.dayofyear-1)/365.25
    v=[np.sin(ang_d),np.cos(ang_d),np.sin(ang_a),np.cos(ang_a),
       valor_climatologia(t,clima)]
    def recuperar(delta):
        p=t-pd.Timedelta(hours=delta)
        x=historico.get(p)
        return float(x) if x is not None and np.isfinite(x) else valor_climatologia(p,clima)
    v.extend(recuperar(lag) for lag in DEFASAGENS_HORAS)
    v.append(float(np.mean([recuperar(j) for j in range(1,25)])))
    return np.asarray(v,dtype=np.float32).reshape(1,-1)


def rf_previsao_recursiva(modelo,datas,historico,clima,observado=None,exibir_progresso=True):
    """Se `observado` existe, atualização diária após prever dia; se None, longo prazo recursivo."""
    previsoes={}
    datas=pd.DatetimeIndex(datas)
    for nd,(dia, grupo) in enumerate(pd.Series(index=datas,dtype='float64').groupby(datas.normalize()),start=1):
        for t in grupo.index:
            est=float(modelo.predict(vetor_para_hora(t,historico,clima))[0])
            est=float(np.clip(est,0,MAX_KJ_M2_H))
            if t.hour in HORAS_NOTURNAS_UTC: est=0.0
            previsoes[t]=est
            historico[t]=est  # somente previsão; o valor observado ainda NÃO foi visto
        if observado is not None:
            # Ao terminar o dia, o real pode ser conhecido para o dia seguinte.
            for t in grupo.index:
                if t in observado.index and pd.notna(observado.loc[t]):
                    historico[t]=float(observado.loc[t])
        if exibir_progresso and nd%90==0:
            print(f'  ... processados {nd} dias (até {grupo.index[-1]:%Y-%m-%d})')
    return pd.Series(previsoes,name='RF_kJ_m2').sort_index()

