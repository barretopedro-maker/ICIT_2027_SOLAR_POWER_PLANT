"""## 10. Métricas e comparação dos modelos (2025)

A métrica principal considera **somente horários verdadeiramente medidos**, excluindo zeros noturnos inferidos e lacunas. `RMSE` e `MAE` são apresentados em kJ/m² (e equivalentes em W/m²). Também calculamos `R²`, `WAPE` e a fração de horas com erro absoluto até a tolerância física fixa. O **MAPE convencional não é adequado** perto de zero; não se interpreta `100 − MAPE` como porcentagem de acerto.
"""

from sklearn.metrics import mean_absolute_error,mean_squared_error,r2_score

def metricas_medidas(real,prev,origem_ref,tolerancia=TOLERANCIA_ACERTO_KJ_M2):
    par=pd.concat([real.rename('real'),prev.rename('prev'),origem_ref.rename('origem')],axis=1)
    par=par.loc[(par.origem=='observado')&par.real.notna()&par.prev.notna()]
    if par.empty:
        return {'N':0,'MAE_kJ_m2':np.nan,'RMSE_kJ_m2':np.nan,'MAE_W_m2':np.nan,
                'RMSE_W_m2':np.nan,'R2':np.nan,'WAPE_pct':np.nan,'Acerto_pct':np.nan}
    er=np.abs(par.real-par.prev)
    mae=float(er.mean());rmse=float(np.sqrt(np.mean((par.real-par.prev)**2)))
    denom=float(np.abs(par.real).sum())
    return {'N':len(par),'MAE_kJ_m2':mae,'RMSE_kJ_m2':rmse,
            'MAE_W_m2':mae/3.6,'RMSE_W_m2':rmse/3.6,
            'R2':float(r2_score(par.real,par.prev)) if len(par)>1 else np.nan,
            'WAPE_pct':float(100*er.sum()/denom) if denom>0 else np.nan,
            'Acerto_pct':float(100*(er<=tolerancia).mean())}

