def chave_coluna(s):
    s = unicodedata.normalize('NFKD', str(s))
    s = ''.join(c for c in s if not unicodedata.combining(c))
    return re.sub(r'[^A-Z0-9]+', '', s.upper())


def localizar_coluna(colunas, prefixo):
    matches = [c for c in colunas if chave_coluna(c).startswith(prefixo)]
    if len(matches) != 1:
        raise ValueError(f'Esperava exatamente 1 coluna {prefixo}, encontrei {matches}. Colunas: {list(colunas)}')
    return matches[0]


def datas_excel_ou_iso(v):
    """Data Excel numeric serial -> dia; datas datetime e strings também aceitas."""
    if pd.isna(v):
        return pd.NaT
    if isinstance(v, (int, float, np.integer, np.floating)) and not isinstance(v, bool):
        return pd.to_datetime(float(v), unit='D', origin='1899-12-30', errors='coerce').normalize()
    return pd.to_datetime(v, errors='coerce', dayfirst=False).normalize()


def hora_utc(v):
    """Retorna (hora, minuto) ou (None, None); não desloca UTC para hora local."""
    if pd.isna(v): return None, None
    if isinstance(v, (pd.Timestamp, datetime, time)):
        return int(v.hour), int(v.minute)
    if isinstance(v, (int, float, np.integer, np.floating)) and not isinstance(v, bool):
        minutos = int(round((float(v) % 1) * 1440))
        if minutos == 1440: minutos = 0
        return minutos // 60, minutos % 60
    st = str(v).strip()
    mat = re.search(r'(?<!\d)(\d{2})(\d{2})(?!\d)', st)
    if mat:
        h, m = map(int, mat.groups())
    else:
        mat = re.search(r'(?<!\d)(\d{1,2}):(\d{2})(?::\d{2})?', st)
        if not mat: return None, None
        h, m = map(int, mat.groups())
    return (h, m) if 0 <= h <= 23 and 0 <= m <= 59 else (None, None)


