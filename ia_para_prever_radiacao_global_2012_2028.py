    if not(AREA_PAINEL_M2>0 and 0<EFICIENCIA_MODULO<=1 and 0<FATOR_DESEMPENHO_PR<=1):
        raise ValueError('Área deve ser > 0 e eficiência/PR devem estar no intervalo (0,1].')


